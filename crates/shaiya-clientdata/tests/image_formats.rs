#[test]
fn jpg_decodes_to_rgba() {
    let img = decode(JPG_RGB, "x.jpg").unwrap();
    assert_eq!((img.width, img.height, img.rgba.len()), (16, 16, 16 * 16 * 4));
    for y in 0..16i32 {
        for x in 0..16i32 {
            let p = &img.rgba[((y * 16 + x) * 4) as usize..][..4];
            assert!(close(p[0], x * 17, 12) && close(p[1], y * 17, 12) && close(p[2], 128, 12) && p[3] == 255, "({x},{y}) = {p:?}");
        }
    }
}

#[test]
fn a_grey_jpg_gets_the_same_value_in_all_colour_channels() {
    let img = decode_jpg(JPG_GREY, "g.jpg").unwrap();
    assert_eq!((img.width, img.height), (16, 16));
    for y in 0..16i32 {
        for x in 0..16i32 {
            let p = &img.rgba[((y * 16 + x) * 4) as usize..][..4];
            let luma = (0.299 * (x * 17) as f32 + 0.587 * (y * 17) as f32 + 0.114 * 128.0).round() as i32;
            assert!(p[0] == p[1] && p[1] == p[2] && p[3] == 255 && close(p[0], luma, 8), "({x},{y}) = {p:?} want {luma}");
        }
    }
}

