#[test]
fn picture_info_reads_jpg_and_png_headers() {
    let p = picture_info(JPG_RGB).unwrap();
    assert_eq!((p.width, p.height, p.what.as_str()), (16, 16, "JPEG baseline, 3 components"));
    assert_eq!(picture_info(JPG_GREY).unwrap().what, "JPEG baseline, 1 component");
    assert_eq!(picture_info(JPG_PROGRESSIVE).unwrap().what, "JPEG progressive, 3 components");
    let png = encode_png(7, 5, png::ColorType::Rgba, png::BitDepth::Eight, &[0; 7 * 5 * 4], None, None);
    let p = picture_info(&png).unwrap();
    assert_eq!((p.width, p.height, p.what.as_str()), (7, 5, "PNG RGBA 8 bit"));
    assert!(picture_info(b"").is_none() && picture_info(&[0xFF, 0xD8]).is_none() && picture_info(b"GIF89a").is_none());
    assert!(picture_info(&png[..20]).is_none());
}

fn encode_png(w: u32, h: u32, ct: png::ColorType, depth: png::BitDepth, data: &[u8], palette: Option<&[u8]>, trns: Option<&[u8]>) -> Vec<u8> {
    let mut out = Vec::new();
    {
        let mut enc = png::Encoder::new(&mut out, w, h);
        enc.set_color(ct);
        enc.set_depth(depth);
        if let Some(p) = palette {
            enc.set_palette(p.to_vec());
        }
        if let Some(t) = trns {
            enc.set_trns(t.to_vec());
        }
        let mut wr = enc.write_header().unwrap();
        wr.write_image_data(data).unwrap();
    }
    out
}

#[test]
fn png_made_by_png_encode_decodes_back() {
    // RGBA 8 bit
    let rgba: Vec<u8> = (0..5 * 3).flat_map(|i| [i as u8 * 10, 255 - i as u8, 7, 100 + i as u8]).collect();
    let png = encode_png(5, 3, png::ColorType::Rgba, png::BitDepth::Eight, &rgba, None, None);
    let img = decode(&png, "a.png").unwrap();
    assert_eq!((img.width, img.height), (5, 3));
    assert_eq!(img.rgba, rgba);
    // RGB gets alpha 255
    let png = encode_png(2, 1, png::ColorType::Rgb, png::BitDepth::Eight, &[1, 2, 3, 4, 5, 6], None, None);
    assert_eq!(decode_png(&png, "b.png").unwrap().rgba, vec![1, 2, 3, 255, 4, 5, 6, 255]);
    // grey and grey + alpha replicate the grey
    let png = encode_png(2, 1, png::ColorType::Grayscale, png::BitDepth::Eight, &[9, 200], None, None);
    assert_eq!(decode_png(&png, "c.png").unwrap().rgba, vec![9, 9, 9, 255, 200, 200, 200, 255]);
    let png = encode_png(1, 1, png::ColorType::GrayscaleAlpha, png::BitDepth::Eight, &[50, 60], None, None);
    assert_eq!(decode_png(&png, "d.png").unwrap().rgba, vec![50, 50, 50, 60]);
    // indexed with a transparency entry
    let png = encode_png(2, 1, png::ColorType::Indexed, png::BitDepth::Eight, &[1, 0], Some(&[10, 20, 30, 40, 50, 60]), Some(&[7, 255]));
    assert_eq!(decode_png(&png, "e.png").unwrap().rgba, vec![40, 50, 60, 255, 10, 20, 30, 7]);
    // 16 bit is reduced to 8
    let png = encode_png(1, 1, png::ColorType::Rgb, png::BitDepth::Sixteen, &[0x12, 0x34, 0x56, 0x78, 0x9a, 0xbc], None, None);
    assert_eq!(decode_png(&png, "f.png").unwrap().rgba, vec![0x12, 0x56, 0x9a, 255]);
    // 1 bit grey
    let png = encode_png(8, 1, png::ColorType::Grayscale, png::BitDepth::One, &[0b1010_0000], None, None);
    let g = decode_png(&png, "g.png").unwrap().rgba;
    assert_eq!((g[0], g[4], g[7]), (255, 0, 255));
}

#[test]
fn a_damaged_picture_is_an_error_and_never_panics() {
    // every prefix and a few corruptions of each file
    let png = encode_png(5, 3, png::ColorType::Rgba, png::BitDepth::Eight, &[3; 60], None, None);
    for file in [JPG_RGB, JPG_GREY, JPG_PROGRESSIVE, &png[..]] {
        for n in (0..file.len()).step_by(7) {
            let _ = decode(&file[..n], "x");
            let _ = picture_info(&file[..n]);
        }
        for i in (0..file.len()).step_by(11) {
            let mut b = file.to_vec();
            b[i] ^= 0x5a;
            let _ = decode(&b, "x");
        }
    }
    assert!(decode_jpg(&[0xFF, 0xD8, 0xFF, 0xD9], "e.jpg").is_err());
    assert!(decode_png(&png[..30], "t.png").is_err());
    assert!(decode_png(b"\x89PNG\r\n\x1a\n", "t.png").is_err());
    // a size far beyond the limit is refused (the frame header claims 65535 x 65535)
    let mut huge = JPG_RGB.to_vec();
    let sof = huge.windows(2).position(|w| w == [0xFF, 0xC0]).unwrap();
    huge[sof + 5..sof + 9].copy_from_slice(&[0xFF, 0xFF, 0xFF, 0xFF]);
    assert!(decode_jpg(&huge, "huge.jpg").is_err());
    let mut huge_png = png.clone();
    huge_png[16..24].copy_from_slice(&[0, 0, 0x9c, 0x40, 0, 0, 0x9c, 0x40]); // 40000 x 40000 (the CRC no longer matches)
    assert!(decode_png(&huge_png, "huge.png").is_err());
}

#[test]
fn a_picture_over_64_mi_pixels_is_refused_by_the_pixel_cap_before_decoding() {
    // 10000 x 10000 is inside the decoder's own side limit (16,384) and over 64 Mi pixels: the refusal must be ours, "out of range"
    let mut big = JPG_RGB.to_vec();
    let sof = big.windows(2).position(|w| w == [0xFF, 0xC0]).unwrap();
    big[sof + 5..sof + 9].copy_from_slice(&[0x27, 0x10, 0x27, 0x10]);
    let e = decode_jpg(&big, "big.jpg").unwrap_err().to_string();
    assert!(e.contains("out of range"), "{e}");
    // a PNG header of the same size with a correct CRC (the chunk checks pass; only the pixel count refuses it)
    fn crc32(bytes: &[u8]) -> u32 {
        let mut c = 0xFFFF_FFFFu32;
        for &b in bytes {
            c ^= u32::from(b);
            for _ in 0..8 {
                c = if c & 1 != 0 { (c >> 1) ^ 0xEDB8_8320 } else { c >> 1 };
            }
        }
        !c
    }
    let mut png = encode_png(5, 3, png::ColorType::Rgba, png::BitDepth::Eight, &[3; 60], None, None);
    png[16..24].copy_from_slice(&[0, 0, 0x27, 0x10, 0, 0, 0x27, 0x10]);
    let crc = crc32(&png[12..29]);
    png[29..33].copy_from_slice(&crc.to_be_bytes());
    let e = decode_png(&png, "big.png").unwrap_err().to_string();
    assert!(e.contains("out of range"), "{e}");
}
