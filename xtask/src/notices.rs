//! `cargo xtask notices [--check]`: generates the Rust-crate part of `THIRD-PARTY-NOTICES.txt` from `cargo metadata`: the crates of the
//! shipped programs grouped by licence expression, then every distinct licence text found in the crates' own files (names starting with
//! LICENSE, LICENCE, COPYING, NOTICE; plus the font licence files of `epaint_default_fonts`), with the SPDX texts in `xtask/licenses/`
//! as the fallback. The hand-written head of the file (Parsec) is kept as it is.

use crate::deps::ALLOWED;
use crate::meta::{load, root, Graph, Pkg};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// The line that starts the generated part.
pub const MARKER: &str = "================================================================================\nRust crates included in the Shaiya Toolkit programs (generated by `cargo xtask notices`; do not edit below this line)\n================================================================================\n";

fn is_notice_name(name: &str) -> bool {
    let n = name.to_ascii_uppercase();
    (n.starts_with("LICENSE") || n.starts_with("LICENCE") || n.starts_with("COPYING") || n.starts_with("NOTICE")) && !n.ends_with(".RS")
}

fn read_text(p: &Path) -> Option<String> {
    let bytes = std::fs::read(p).ok()?;
    let text = String::from_utf8_lossy(&bytes).replace("\r\n", "\n");
    let t = text.trim().to_string();
    (!t.is_empty()).then_some(t)
}

/// The licence and notice files of a crate: (file name, text), sorted by name.
pub fn crate_texts(pkg: &Pkg) -> Vec<(String, String)> {
    let dir = pkg.dir();
    let mut out = Vec::new();
    let mut add_dir = |d: &Path, pick: &dyn Fn(&str) -> bool| {
        let Ok(rd) = std::fs::read_dir(d) else { return };
        let mut names: Vec<String> = rd.flatten().filter(|e| e.path().is_file()).map(|e| e.file_name().to_string_lossy().into_owned()).collect();
        names.sort();
        for n in names {
            if pick(&n) {
                if let Some(t) = read_text(&d.join(&n)) {
                    out.push((n, t));
                }
            }
        }
    };
    add_dir(&dir, &is_notice_name);
    if pkg.name == "epaint_default_fonts" {
        add_dir(&dir.join("fonts"), &|n| n.to_ascii_lowercase().ends_with(".txt"));
    }
    out
}

fn fallback_dir() -> PathBuf {
    root().join("xtask").join("licenses")
}

/// A fallback SPDX text for a licence expression: the first allowed alternative that has a file in `xtask/licenses/`.
fn fallback_text(expr: &str) -> Option<(String, String)> {
    let mut ids: Vec<&str> = ALLOWED.to_vec();
    ids.sort_by_key(|i| if *i == "MIT" { 0 } else { 1 });
    for id in ids {
        if !expr.split(|c: char| c.is_whitespace() || c == '(' || c == ')' || c == '/').any(|t| t == id) {
            continue;
        }
        if let Some(t) = read_text(&fallback_dir().join(format!("{id}.txt"))) {
            return Some((format!("{id}.txt (SPDX text)"), t));
        }
    }
    None
}

/// The generated part of the file for a graph.
pub fn generate(g: &Graph) -> Result<String, String> {
    let mut by_license: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut texts: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut missing = Vec::new();
    let mut pkgs: Vec<&Pkg> = g.shipped.iter().map(|id| &g.packages[id]).filter(|p| !p.is_workspace).collect();
    pkgs.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));
    for p in pkgs {
        let label = format!("{} {}", p.name, p.version);
        let expr = p.license.clone().unwrap_or_else(|| "UNKNOWN".into());
        by_license.entry(expr.clone()).or_default().push(label.clone());
        let mut found = crate_texts(p);
        if found.is_empty() {
            match fallback_text(&expr) {
                Some(f) => found.push(f),
                None => missing.push(format!("{label} ({expr})")),
            }
        }
        for (_, t) in found {
            texts.entry(t).or_default().push(label.clone());
        }
    }
    if !missing.is_empty() {
        return Err(format!("no licence text found for: {}; add the SPDX text to xtask/licenses/<id>.txt", missing.join(", ")));
    }
    let mut out = String::from(MARKER);
    out.push_str("\nCrates by licence (name and version, as locked in Cargo.lock):\n");
    for (expr, crates) in &by_license {
        out.push_str(&format!("\n{expr}  ({} crates)\n", crates.len()));
        for c in crates {
            out.push_str(&format!("  {c}\n"));
        }
    }
    out.push_str("\n\nLicence and notice texts\n------------------------\n");
    let mut ordered: Vec<(&String, &Vec<String>)> = texts.iter().collect();
    ordered.sort_by(|a, b| (a.1.first(), a.0).cmp(&(b.1.first(), b.0)));
    for (text, users) in ordered {
        let mut users = users.clone();
        users.dedup();
        out.push_str(&format!("\n--- used by: {}\n\n{text}\n", users.join(", ")));
    }
    Ok(out)
}

/// The head of an existing file: everything before the marker (or all of it when there is no marker), ending in one newline.
pub fn head_of(existing: &str) -> String {
    let existing = existing.replace("\r\n", "\n");
    let head = match existing.find(MARKER) {
        Some(i) => &existing[..i],
        None => existing.as_str(),
    };
    format!("{}\n\n", head.trim_end())
}

pub fn run(check: bool) -> Result<(), String> {
    let g = load()?;
    let path = root().join("THIRD-PARTY-NOTICES.txt");
    let existing = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let full = format!("{}{}", head_of(&existing), generate(&g)?);
    if check {
        if existing.replace("\r\n", "\n") == full {
            println!("notices: THIRD-PARTY-NOTICES.txt is up to date");
            Ok(())
        } else {
            Err("THIRD-PARTY-NOTICES.txt is out of date: run `cargo xtask notices` and commit the result".into())
        }
    } else {
        std::fs::write(&path, &full).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("notices: wrote {} ({} bytes)", path.display(), full.len());
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notice_file_names() {
        for n in ["LICENSE", "LICENSE-MIT", "license-apache", "LICENCE.txt", "COPYING", "NOTICE", "NOTICE.md", "UNLICENSE"] {
            assert_eq!(is_notice_name(n), n != "UNLICENSE", "{n}");
        }
        assert!(!is_notice_name("license.rs"));
        assert!(!is_notice_name("Cargo.toml"));
    }

    #[test]
    fn the_head_is_kept_and_the_generated_part_replaced() {
        let existing = format!("hand written\r\nhead\n\n{MARKER}\nold generated stuff\n");
        assert_eq!(head_of(&existing), "hand written\nhead\n\n");
        assert_eq!(head_of("only a head\n"), "only a head\n\n");
        // regenerating twice keeps the head stable
        let once = format!("{}{MARKER}x", head_of("head"));
        assert_eq!(head_of(&once), "head\n\n");
    }

    #[test]
    fn fallbacks_prefer_mit() {
        // the committed SPDX files exist for the common licences
        let (name, text) = fallback_text("Apache-2.0 OR MIT").expect("MIT fallback");
        assert!(name.starts_with("MIT"), "{name}");
        assert!(text.contains("Permission is hereby granted"));
        assert!(fallback_text("GPL-3.0").is_none());
    }
}
